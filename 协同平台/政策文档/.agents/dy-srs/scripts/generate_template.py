def main():
    parser = argparse.ArgumentParser(description='生成 SRS 文档模板')
    parser.add_argument('--output', '-o', required=True, help='输出目录路径')
    parser.add_argument('--project', '-p', required=True, help='项目名称')
    parser.add_argument('--filename', '-f', default='SRS.md', help='输出文件名（默认: SRS.md）')

    args = parser.parse_args()

    # 确保输出目录存在
    os.makedirs(args.output, exist_ok=True)

    # 生成模板
    template = generate_srs_template(args.project)

    # 写入文件
    output_path = os.path.join(args.output, args.filename)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(template)

    print(f'✅ SRS 模板已生成: {output_path}')


if __name__ == '__main__':
    main()
